// Albanian-aware slugifier. Strips diacritics, lowercases, replaces
// non-alphanumerics with hyphens, collapses repeats.
export function slugify(input: string): string {
  return input
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 80);
}
